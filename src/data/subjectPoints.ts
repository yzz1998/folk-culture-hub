const BY_SUBJECT = new Map<Subject, SubjectPointLink[]>()
for (const link of SUBJECT_POINTS) {
  const list = BY_SUBJECT.get(link.subject) ?? []
  list.push(link)
  BY_SUBJECT.set(link.subject, list)
}

const BY_POINT = new Map<string, SubjectPointLink[]>()
for (const link of SUBJECT_POINTS) {
  const list = BY_POINT.get(link.pointId) ?? []
  list.push(link)
  BY_POINT.set(link.pointId, list)
}

export function linksOfSubject(subject: Subject): SubjectPointLink[] {
  return BY_SUBJECT.get(subject) ?? []
}

export function linksOfPoint(pointId: string): SubjectPointLink[] {
  return BY_POINT.get(pointId) ?? []
}

/** 该学科借用了多少个知识点 */
export function pointCountOfSubject(subject: Subject): number {
  return (BY_SUBJECT.get(subject) ?? []).length
}

/** 每个知识点至少被一个学科引用——辅助层不留孤儿 */
export function orphanPointIds(): string[] {
  return CURRICULUM.flatMap((c) => c.units.flatMap((u) => u.points.map((p) => p.id))).filter(
    (id) => !BY_POINT.has(id),
  )
}
