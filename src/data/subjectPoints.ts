/* ═══════════════════════════════════════════════════════════════
   学科 ↔ 知识点：唯一的跨层入口

   这份表回答的是「这门学科可以借用《人类与社会》的哪个知识点来做什么」，
   不回答「这门学科教什么」——学科主线在 types.ts 的 SUBJECT_META 里。

   编写纪律：
   - why 必须点名学科侧的具体内容（如「为『图形的运动』提供轴对称样例」），
     禁止「有助于培养文化认同」这类万能句。
   - 借用必须是可选的。某学科一条都没有，是合法状态，不要为凑数硬挂。
   - 英语、信息科技的 affinity 为 none，只允许 context / contrast，
     且只作文化背景或对比材料，不得成为课程主题。
   ═══════════════════════════════════════════════════════════════ */

const L = (subject: Subject, rows: [PointId, PointUse, string][]): SubjectPointLink[] =>
  rows.map(([pointId, use, why]) => ({ subject, pointId, use, why }))

