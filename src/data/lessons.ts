export const FOLK_FUSION_LESSONS: LessonPlan[] = LESSONS

/** 与民俗无关、按学科自身主线设计的课例 */
export const STANDALONE_LESSONS: LessonPlan[] = SUBJECT_LESSONS

/** 取一份课例的民俗关联方式，未标注时按是否引用民俗推断 */
export function folkLinkOf(l: LessonPlan) {
  return l.folkLink ?? (l.folkIds.length > 0 ? 'core' : 'none')
}

export const LESSON_MAP = new Map(ALL_LESSONS.map((l) => [l.id, l]))

export function getLesson(id: string | undefined): LessonPlan | undefined {
  return id ? LESSON_MAP.get(id) : undefined
}

export function lessonsByFolk(folkId: string): LessonPlan[] {
  return ALL_LESSONS.filter((l) => l.folkIds.includes(folkId))
}

export function lessonsByGrade(band: string): LessonPlan[] {
  return ALL_LESSONS.filter((l) => l.gradeBand === band)
}

export function lessonsBySubject(subject: string): LessonPlan[] {
  return ALL_LESSONS.filter((l) => l.subject === subject)
}

/** 各学科的课例数，用于教学应用页与空态判断 */
export function lessonCountBySubject(): Record<string, { total: number; standalone: number }> {
  const out: Record<string, { total: number; standalone: number }> = {}
  for (const l of ALL_LESSONS) {
    const cur = out[l.subject] ?? { total: 0, standalone: 0 }
    cur.total += 1
    if (folkLinkOf(l) === 'none') cur.standalone += 1
    out[l.subject] = cur
  }
  return out
}
